// Country -> default language mapping used for automatic locale detection
// (e.g. on public payment pages where the buyer's country is known from the
// `country` query param / merchant country / link country).
const FRENCH_COUNTRIES = new Set([
  "togo", "benin", "bénin", "senegal", "sénégal", "ivory coast", "côte d'ivoire",
  "cote d'ivoire", "mali", "burkina faso", "niger", "guinea", "guinée",
  "cameroon", "cameroun", "gabon", "congo", "drc", "rdc", "chad", "tchad",
  "madagascar", "comoros", "comores", "djibouti", "france", "haiti", "haïti",
]);

const CHINESE_COUNTRIES = new Set([
  "china", "chine", "hong kong", "hongkong", "macau", "macao", "taiwan",
]);

const PORTUGUESE_COUNTRIES = new Set([
  "portugal", "brazil", "brésil", "bresil", "angola", "mozambique",
  "guinea-bissau", "cape verde", "cap-vert",
]);

const HINDI_COUNTRIES = new Set([
  "india", "inde",
]);

export function detectLangFromCountry(country?: string | null): Lang {
  if (!country) return "en";
  const key = country.trim().toLowerCase();
  if (FRENCH_COUNTRIES.has(key)) return "fr";
  if (CHINESE_COUNTRIES.has(key)) return "zh";
  if (PORTUGUESE_COUNTRIES.has(key)) return "pt";
  if (HINDI_COUNTRIES.has(key)) return "hi";
  // Pakistan, Nigeria, Ghana, Kenya, USA, UK, etc. => English
  return "en";
}

// Best-effort detection from the browser when no country is known
// (e.g. crypto payment pages with no country field).
export function detectLangFromBrowser(): Lang {
  if (typeof navigator === "undefined") return "en";
  const locale = (navigator.language || (navigator as any).userLanguage || "en").toLowerCase();
  if (locale.startsWith("fr")) return "fr";
  if (locale.startsWith("zh")) return "zh";
  if (locale.startsWith("pt")) return "pt";
  if (locale.startsWith("hi")) return "hi";
  return "en";
}

