interface LanguageContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  currentLanguage: { code: Lang; label: string; flag: string };
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

function readStoredLang(): Lang | null {
  if (typeof window === "undefined") return null;
  const saved = localStorage.getItem("westpay_lang");
  if (saved === "fr" || saved === "en" || saved === "pt" || saved === "zh" || saved === "hi") return saved;
  return null;
}

export function translateForCurrentLanguage(key: string): string {
  const lang = readStoredLang() || "en";
  return translations[lang][key] || translations.en[key] || translations.fr[key] || key;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readStoredLang() || "en");

  const setLang = (newLang: Lang) => {
    setLangState(newLang);
    localStorage.setItem("westpay_lang", newLang);
    localStorage.setItem("westpay_lang_explicit", "1");
  };

  // Auto-detect language once from country (used by public pay pages) unless
  // the user has already explicitly picked a language before.
  const autoSetLangFromCountry = (country?: string | null) => {
    if (localStorage.getItem("westpay_lang_explicit") === "1") return;
    const detected = detectLangFromCountry(country);
    setLangState(detected);
    localStorage.setItem("westpay_lang", detected);
  };

  const autoSetLangFromBrowser = () => {
    if (localStorage.getItem("westpay_lang_explicit") === "1") return;
    const detected = detectLangFromBrowser();
    setLangState(detected);
    localStorage.setItem("westpay_lang", detected);
  };

  // Sets a default language without marking the choice as explicit, so
  // later auto-detection (by country/browser) can still override it.
  const setDefaultLang = (newLang: Lang) => {
    if (localStorage.getItem("westpay_lang_explicit") === "1") return;
    setLangState(newLang);
    localStorage.setItem("westpay_lang", newLang);
  };

  const t = (key: string): string => {
    return translations[lang][key] || translations["en"][key] || translations["fr"][key] || key;
  };

  const currentLanguage = LANGUAGES.find(l => l.code === lang) || LANGUAGES[0];

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, currentLanguage, autoSetLangFromCountry, autoSetLangFromBrowser, setDefaultLang } as any}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx as LanguageContextType & {
    autoSetLangFromCountry: (country?: string | null) => void;
    autoSetLangFromBrowser: () => void;
    setDefaultLang: (lang: Lang) => void;
  };
}
